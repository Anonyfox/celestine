"""Generate src/precise/<body>-data.ts (shared format, see src/precise/chebyshev.ts).
usage: python3 -W ignore gen-cheb.py <body> <deg> <tol_arcsec> <quantum_AU> <grain_days> [<dir>]
Model: mean Kepler orbit (12 params, least squares over 1800-2200) + adaptive Chebyshev fit of the
spherical residual (dlon*scale, dlat*scale, dr). z/r degree = deg-2. Training rows = even rows of the
2-day Horizons grid plus segment endpoints; held-out = the remaining odd rows."""
import sys, json, numpy as np
from fitlib import Body, adaptive, pack_ints, J0
from kep import kepler_xyz
import sweep_base
SCALE={'chiron':13.6,'ceres':2.77,'pallas':2.77,'juno':2.67,'vesta':2.36}
FULL={'chiron':'2060 Chiron','ceres':'1 Ceres','pallas':'2 Pallas','juno':'3 Juno','vesta':'4 Vesta'}
name=sys.argv[1]; deg=int(sys.argv[2]); tol=float(sys.argv[3]); q=float(sys.argv[4]); grain=int(sys.argv[5])
outdir=sys.argv[6] if len(sys.argv)>6 else '../../src/precise'
p=[float(v) for v in sweep_base.base_params(name)]
B=Body(name,lambda t: kepler_xyz(np.array(p),t),sph=True,scale=SCALE[name])
ns=(deg,deg,deg-2)
segs,e=adaptive(B,ns,tol,q,grain)
ints=pack_ints(segs,grain)
def zz(v): return v*2 if v>=0 else -v*2-1
s=[]
for v in ints:
    z=zz(int(v))
    while True:
        g=z&31; z>>=5
        if z: s.append(chr(48+g))
        else: s.append(chr(93+g)); break
s=''.join(s); assert '\\' not in s and "'" not in s
end=J0+sum(L for L,_ in segs)
U=name.upper()
src=f"""// Generated by scripts/chiron/gen-cheb.py from JPL Horizons vectors ({FULL[name]}, heliocentric,
// ecliptic J2000, TDB, 2-day grid). Do not edit by hand.
// {len(segs)} segments, degrees {ns[0]}/{ns[1]}/{ns[2]}, quantum {q:g} AU, JD {J0}-{end};
// grid held-out max geocentric error {e.max():.2f} arcsec (RMS {np.sqrt((e**2).mean()):.2f}).
import type {{ ChebyshevModel }} from './chebyshev.js';

export const {U}_CHEBYSHEV: ChebyshevModel = {{
  start: {J0},
  grain: {grain},
  quantum: {q:g},
  scale: {SCALE[name]},
  degrees: [{ns[0]}, {ns[1]}, {ns[2]}],
  kepler: [
{chr(10).join('    '+repr(v)+',' for v in p)}
  ],
  data:
    '{s}',
}};
"""
open(f'{outdir}/{name}-data.ts','w').write(src)
import subprocess; subprocess.run(['npx','biome','format','--write',f'{outdir}/{name}-data.ts'],capture_output=True)
json.dump({'name':name,'deg':ns,'tol':tol,'q':q,'grain':grain,'segs':len(segs),'end':end,'held_max':float(e.max()),'held_rms':float(np.sqrt((e**2).mean())),'chars':len(s)},open(f'model-{name}.json','w'))
print(name,'segs',len(segs),'end',end,'held max %.3f rms %.3f'%(e.max(),np.sqrt((e**2).mean())),'chars',len(s))
