export function getSaturnPosition(jd: number, options: EphemerisOptions = {}): PlanetPosition {
  return geocentricApparent(saturnHeliocentric, jd, options, 0.01);
}

function saturnHeliocentric(jd: number) {
  const tau = (jd - 2451545) / 365250;
  return {
    longitude: saturnHeliocentricLongitude(tau),
    latitude: saturnHeliocentricLatitude(tau),
    distance: saturnHeliocentricDistance(tau),
    velocity: heliocentricVelocity(L0, B0, R0, L1[0][0], tau),
  };
}

