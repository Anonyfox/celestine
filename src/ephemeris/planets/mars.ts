export function getMarsPosition(jd: number, options: EphemerisOptions = {}): PlanetPosition {
  return geocentricApparent(marsHeliocentric, jd, options, 1);
}

function marsHeliocentric(jd: number) {
  const tau = (jd - 2451545) / 365250;
  return {
    longitude: marsHeliocentricLongitude(tau),
    latitude: marsHeliocentricLatitude(tau),
    distance: marsHeliocentricDistance(tau),
    velocity: heliocentricVelocity(L0, B0, R0, L1[0][0], tau),
  };
}

