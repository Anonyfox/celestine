export function getJupiterPosition(jd: number, options: EphemerisOptions = {}): PlanetPosition {
  return geocentricApparent(jupiterHeliocentric, jd, options, 1);
}

function jupiterHeliocentric(jd: number) {
  const tau = (jd - 2451545) / 365250;
  return {
    longitude: jupiterHeliocentricLongitude(tau),
    latitude: jupiterHeliocentricLatitude(tau),
    distance: jupiterHeliocentricDistance(tau),
    velocity: heliocentricVelocity(L0, B0, R0, L1[0][0], tau),
  };
}

